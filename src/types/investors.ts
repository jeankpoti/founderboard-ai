/**
 * Where is this investor in your fundraising pipeline?
 *
 * The pipeline represents the journey from first contact to closed deal:
 *
 * 1. lead: You've identified them as a potential investor
 * 2. contacted: You've reached out (cold email, intro, etc.)
 * 3. meeting_scheduled: You have a meeting on the calendar
 * 4. in_discussion: Active conversations happening
 * 5. due_diligence: They're doing deep dive on your company
 * 6. term_sheet: They've sent a term sheet (offer to invest)
 * 7. closed: Deal is done, money in bank!
 * 8. passed: They decided not to invest (not a bad thing - it's data)
 */
export type InvestorStage =
  | 'lead'
  | 'contacted'
  | 'meeting_scheduled'
  | 'in_discussion'
  | 'due_diligence'
  | 'term_sheet'
  | 'closed'
  | 'passed'

