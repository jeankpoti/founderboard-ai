/**
 * Schema for creating a new investor.
 * Zod validates all the data before we save it.
 */
export const createInvestorSchema = z.object({
  name: z
    .string()
    .min(1, 'Name is required')
    .max(200, 'Name must be 200 characters or less'),

  type: z.enum(INVESTOR_TYPES as [InvestorType, ...InvestorType[]]),

  firm: z.string().max(200).optional(),

  email: z.string().email('Invalid email address').optional().or(z.literal('')),

  phone: z.string().max(50).optional(),

  linkedInUrl: z.string().url('Invalid URL').optional().or(z.literal('')),

  twitterHandle: z.string().max(50).optional(),

  website: z.string().url('Invalid URL').optional().or(z.literal('')),

  stage: z
    .enum(INVESTOR_STAGES as [InvestorStage, ...InvestorStage[]])
    .default('lead'),

  checkSize: z
    .object({
      min: z.number().min(0),
      max: z.number().min(0),
      currency: z.string().default('USD'),
    })
    .optional(),

  focusAreas: z.array(z.string()).optional(),

  investmentStages: z.array(z.string()).optional(),

  notes: z.string().max(10000).optional(),

  assigneeId: z.string().optional(),

  nextFollowUpAt: z.string().optional(),

  source: z.string().max(200).optional(),

  referredBy: z.string().max(200).optional(),

  priority: z.enum(['low', 'medium', 'high']).optional(),
})

/**
 * Schema for updating an investor.
 * All fields are optional since you might only update one thing.
 */
export const updateInvestorSchema = createInvestorSchema.partial()

/**
 * Schema for creating a meeting.
 */
export const createMeetingSchema = z.object({
  investorId: z.string().min(1, 'Investor is required'),

  title: z
    .string()
    .min(1, 'Title is required')
    .max(200, 'Title must be 200 characters or less'),

  description: z.string().max(5000).optional(),

  meetingType: z.enum(MEETING_TYPES as [MeetingType, ...MeetingType[]]),

  scheduledAt: z.string().min(1, 'Date/time is required'),

  duration: z.number().min(15).max(480).default(60), // 15 min to 8 hours

  location: z.string().max(500).optional(),

  meetingUrl: z.string().url('Invalid URL').optional().or(z.literal('')),

  attendees: z.array(z.string()).optional(),
})

