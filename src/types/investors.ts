/**
 * Investors grouped by pipeline stage (for Kanban view)
 */
export type InvestorsByStage = Record<InvestorStage, Investor[]>

/**
 * Group investors by their pipeline stage.
 *
 * @param investors - Array of investors to group
 * @returns Object with stages as keys and investor arrays as values
 */
export function groupInvestorsByStage(investors: Investor[]): InvestorsByStage {
  // Initialize all stages with empty arrays
  const grouped: InvestorsByStage = {
    lead: [],
    contacted: [],
    meeting_scheduled: [],
    in_discussion: [],
    due_diligence: [],
    term_sheet: [],
    closed: [],
    passed: [],
  }

  // Place each investor in the right group
  investors.forEach((investor) => {
    grouped[investor.stage].push(investor)
  })

  return grouped
}

/**
 * Get statistics about your investor pipeline.
 *
 * @param investors - Array of investors
 * @returns Stats object with counts and percentages
 */
export function getInvestorStats(investors: Investor[]) {
  const total = investors.length
  const byStage = groupInvestorsByStage(investors)

  // Count active (not passed or closed)
  const active = investors.filter(
    (i) => i.stage !== 'passed' && i.stage !== 'closed'
  ).length

  // Count needing follow-up (next follow-up date in the past)
  const now = new Date()
  const needsFollowUp = investors.filter((i) => {
    if (!i.nextFollowUpAt) return false
    return new Date(i.nextFollowUpAt) < now
  }).length

  return {
    total,
    active,
    needsFollowUp,
    byStage: {
      lead: byStage.lead.length,
      contacted: byStage.contacted.length,
      meeting_scheduled: byStage.meeting_scheduled.length,
      in_discussion: byStage.in_discussion.length,
      due_diligence: byStage.due_diligence.length,
      term_sheet: byStage.term_sheet.length,
      closed: byStage.closed.length,
      passed: byStage.passed.length,
    },
    // Conversion rate: closed / (closed + passed)
    conversionRate:
      byStage.closed.length + byStage.passed.length > 0
        ? Math.round(
            (byStage.closed.length /
              (byStage.closed.length + byStage.passed.length)) *
              100
          )
        : 0,
  }
}
