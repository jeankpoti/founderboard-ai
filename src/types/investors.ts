/**
 * What type of investor is this?
 *
 * Different investor types have different characteristics:
 * - Angel: Individual investors, usually write smaller checks ($10K-$250K)
 * - VC: Venture Capital firms, larger checks ($500K-$50M+)
 * - Family Office: Wealthy family's investment arm
 * - Corporate: Company investing strategically (e.g., Google Ventures)
 * - Accelerator: Programs like Y Combinator that invest + provide support
 */
export type InvestorType =
  | 'angel'
  | 'vc'
  | 'family_office'
  | 'corporate'
  | 'accelerator'
  | 'other'

