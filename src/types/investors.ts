/**
 * The main Investor interface.
 *
 * This represents an investor contact in your CRM.
 * Think of it like a detailed contact card.
 */
export interface Investor {
  /** Unique identifier (auto-generated by Firestore) */
  id: string

  /** Which organization this investor belongs to */
  orgId: string

  /** Investor's full name */
  name: string

  /** Type of investor (angel, VC, etc.) */
  type: InvestorType

  /** Their firm/company name (optional - angels might not have one) */
  firm?: string

  /** Email address for contact */
  email?: string

  /** Phone number */
  phone?: string

  /** LinkedIn profile URL */
  linkedInUrl?: string

  /** Twitter/X handle */
  twitterHandle?: string

  /** Their website */
  website?: string

  /** Current stage in your pipeline */
  stage: InvestorStage

  /**
   * Their typical check size range
   * Example: { min: 100000, max: 500000, currency: 'USD' }
   */
  checkSize?: {
    min: number
    max: number
    currency: string
  }

  /**
   * What areas/industries do they focus on?
   * Example: ['fintech', 'saas', 'b2b']
   */
  focusAreas?: string[]

  /**
   * What stage companies do they invest in?
   * Example: ['pre-seed', 'seed']
   */
  investmentStages?: string[]

  /** Free-form notes about this investor */
  notes?: string

  /** Who on your team is responsible for this relationship */
  assigneeId?: string
  assigneeName?: string

  /** When was the last interaction with this investor */
  lastContactAt?: string

  /** When should you follow up next */
  nextFollowUpAt?: string

  /** How did you find this investor? (referral, cold outreach, etc.) */
  source?: string

  /** Who referred them (if applicable) */
  referredBy?: string

  /** Priority level for outreach */
  priority?: 'low' | 'medium' | 'high'

  /** User who created this record */
  createdBy: string

  /** Timestamps (ISO strings for serialization) */
  createdAt: string
  updatedAt: string
}

