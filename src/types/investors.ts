/**
 * Investor Types & Schemas
 *
 * This file defines all data structures for the Investor CRM feature.
 *
 * WHAT IS A CRM?
 * - CRM stands for Customer Relationship Management
 * - For founders, we track INVESTOR relationships instead of customers
 * - It helps you keep track of who you've talked to, meeting notes, and next steps
 *
 * KEY CONCEPTS:
 * - Investor: A person/firm who might invest in your company
 * - Pipeline: The journey from "lead" to "closed" (like a sales funnel)
 * - Meeting: A scheduled call or meeting with an investor
 * - Interaction: Any touchpoint (email, call, note)
 */

